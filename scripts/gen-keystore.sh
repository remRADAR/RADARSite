#!/usr/bin/env bash
#
# Generate the release keystore for RADARSite (Q1 from the Phase 2 record).
#
# The keystore and its passwords must be stored in a secrets manager and backed up.
# Losing them means the app can never be updated on Play under the same identity.
#
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
KS="$ROOT/android/radarsite-release.jks"
PROPS="$ROOT/android/keystore.properties"

command -v keytool >/dev/null || { echo "keytool not found (install JDK 21)"; exit 1; }

if [ -f "$KS" ]; then
  echo "Keystore already exists at $KS — not overwriting."
  echo "Delete it manually if you really intend to create a new signing identity."
  exit 0
fi

read -rsp "Keystore password: " STOREPASS; echo
read -rsp "Confirm password:  " STOREPASS2; echo
[ "$STOREPASS" = "$STOREPASS2" ] || { echo "Passwords do not match."; exit 1; }

keytool -genkeypair \
  -v \
  -keystore "$KS" \
  -alias radarsite \
  -keyalg RSA \
  -keysize 4096 \
  -validity 10000 \
  -storepass "$STOREPASS" \
  -keypass "$STOREPASS" \
  -dname "CN=RADARCharts, OU=Mobile, O=RADARCharts, L=Lagos, C=NG"

cat > "$PROPS" <<EOF
# NOT committed. Generated by scripts/gen-keystore.sh
storeFile=keystore/placeholder
storePassword=$STOREPASS
keyAlias=radarsite
keyPassword=$STOREPASS
EOF

# storeFile must be relative to the android/ module root
sed -i "s|storeFile=.*|storeFile=radarsite-release.jks|" "$PROPS"

echo
echo "Created:"
echo "  $KS"
echo "  $PROPS  (git-ignored)"
echo
echo "Back both up now. They cannot be regenerated."
